using DressSharp.CommandLine;
using Xunit;

namespace DressSharp.UnitTests;

public sealed class FileSelectorTests : IDisposable
{
    readonly string directory = Directory.CreateDirectory(
        Path.Combine(Path.GetTempPath(), "DressSharp.UnitTests", Guid.NewGuid().ToString("N"))).FullName;

    [Fact]
    public async Task Empty_operands_recursively_select_eligible_files_in_display_order()
    {
        Write("z.cs", "class Z {}");
        Write("a.cs", "class A {}");
        Write("notes.txt", "no");
        Write("obj/code.g.cs", "class Generated {}");
        Write("header.cs", "// <auto-generated />\nclass Generated {}");
        Write(".git/hidden.cs", "class Hidden {}");

        var selected = await Select();

        Assert.Equal(["a.cs", "z.cs"], selected.Select(file => file.DisplayPath));
    }

    [Fact]
    public async Task Explicit_generated_file_is_excluded_but_unsupported_file_fails()
    {
        Write("code.designer.cs", "class Generated {}");
        Write("notes.txt", "no");

        Assert.Empty(await Select("code.designer.cs"));
        var exception = await Assert.ThrowsAsync<FileSelectionException>(() => Select("notes.txt"));
        Assert.Contains("Unsupported file path", exception.Message);
    }

    [Fact]
    public async Task Overlapping_inputs_are_canonicalized()
    {
        Write("src/code.cs", "class C {}");

        var selected = await Select("src", "src/code.cs", ".");

        Assert.Single(selected);
        Assert.Equal("src/code.cs", selected[0].DisplayPath);
    }

    [Fact]
    public async Task Nested_gitignore_rules_and_negation_are_honored()
    {
        Write(".gitignore", "ignored/\n*.skip.cs\n!keep.skip.cs\n");
        Write("ignored/no.cs", "class No {}");
        Write("drop.skip.cs", "class Drop {}");
        Write("keep.skip.cs", "class Keep {}");
        Write("nested/.gitignore", "*.cs\n!yes.cs\n");
        Write("nested/no.cs", "class No {}");
        Write("nested/yes.cs", "class Yes {}");

        var selected = await Select();

        Assert.Equal(["keep.skip.cs", "nested/yes.cs"], selected.Select(file => file.DisplayPath));
    }

    [Theory]
    [InlineData("-")]
    [InlineData("*.cs")]
    [InlineData("missing.cs")]
    public async Task Invalid_operands_fail_preflight(string operand)
    {
        await Assert.ThrowsAsync<FileSelectionException>(() => Select(operand));
    }

    Task<IReadOnlyList<SelectedFile>> Select(params string[] operands) =>
        new FileSelector(directory).SelectAsync(operands, TestContext.Current.CancellationToken);

    void Write(string relativePath, string text)
    {
        var path = Path.Combine(directory, relativePath.Replace('/', Path.DirectorySeparatorChar));
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, text);
    }

    public void Dispose()
    {
        Directory.Delete(directory, true);
        GC.SuppressFinalize(this);
    }
}
